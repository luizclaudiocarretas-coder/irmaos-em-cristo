create table if not exists public.episodes (
  id bigint generated by default as identity primary key,
  title text not null,
  description text default '',
  category text default 'Pregação',
  audio_url text not null,
  storage_path text not null,
  created_at timestamptz not null default now()
);
alter table public.episodes enable row level security;
drop policy if exists "Public can read episodes" on public.episodes;
create policy "Public can read episodes" on public.episodes for select to anon, authenticated using (true);
drop policy if exists "Authenticated admins can add episodes" on public.episodes;
create policy "Authenticated admins can add episodes" on public.episodes for insert to authenticated with check (true);
drop policy if exists "Authenticated admins can delete episodes" on public.episodes;
create policy "Authenticated admins can delete episodes" on public.episodes for delete to authenticated using (true);

insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
values ('podcasts','podcasts',true,104857600,array['audio/mpeg','audio/mp4','audio/aac','audio/ogg','audio/wav','audio/x-wav','audio/m4a'])
on conflict (id) do update set public=true,file_size_limit=104857600,allowed_mime_types=excluded.allowed_mime_types;
drop policy if exists "Public can listen to podcast files" on storage.objects;
create policy "Public can listen to podcast files" on storage.objects for select to anon,authenticated using (bucket_id='podcasts');
drop policy if exists "Authenticated admins can upload podcast files" on storage.objects;
create policy "Authenticated admins can upload podcast files" on storage.objects for insert to authenticated with check (bucket_id='podcasts');
drop policy if exists "Authenticated admins can delete podcast files" on storage.objects;
create policy "Authenticated admins can delete podcast files" on storage.objects for delete to authenticated using (bucket_id='podcasts');
